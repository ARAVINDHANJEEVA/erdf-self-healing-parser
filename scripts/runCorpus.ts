/**
 * Standalone benchmark execution script.
 * Runs evaluation across the corpus, displays summary table, and exports raw results.
 */

import fs from 'fs';
import path from 'path';
import { generateBenchmarkCorpus } from '../src/corpus/mutator';
import { evaluateCorpus } from '../src/corpus/evaluator';

export function runBenchmark() {
  console.log('Generating MiniLang benchmark corpus...');
  const cases = generateBenchmarkCorpus();
  console.log(`Generated ${cases.length} mutated benchmark cases.\n`);

  console.log('Evaluating recovery strategies...');
  const summary = evaluateCorpus(cases);

  console.log('\n================== BENCHMARK RESULTS SUMMARY ==================');
  console.table(
    summary.strategies.map((s) => ({
      Strategy: s.strategyName,
      Cases: s.totalCases,
      'Recovery Rate': `${s.recoveryRate}%`,
      'Oracle Match': `${s.exactMatchRate}%`,
      'Avg Cost': s.averageCost,
      'Mean Latency': `${s.meanLatencyMs}ms`,
    }))
  );

  // Write results to disk
  const resultsDir = path.resolve(process.cwd(), 'results');
  if (!fs.existsSync(resultsDir)) {
    fs.mkdirSync(resultsDir, { recursive: true });
  }

  const jsonPath = path.join(resultsDir, 'corpus-results.json');
  fs.writeFileSync(jsonPath, JSON.stringify(summary, null, 2), 'utf-8');
  console.log(`\nRaw results saved to: ${jsonPath}`);

  const mdPath = path.join(resultsDir, 'corpus-summary.md');
  const markdown = `# MiniLang Syntax Recovery Benchmark Results

**Timestamp**: ${summary.timestamp}  
**Corpus Size**: ${summary.corpusSize} mutated cases  

## Comparative Strategy Performance

| Strategy | Recovery Rate | Exact Oracle Match | Avg Edit Cost | Mean Latency |
| :--- | :---: | :---: | :---: | :---: |
${summary.strategies
  .map(
    (s) =>
      `| **${s.strategyName}** | ${s.recoveryRate}% | ${s.exactMatchRate}% | ${s.averageCost} | ${s.meanLatencyMs}ms |`
  )
  .join('\n')}

---
*Generated by ERDF Evaluation Harness.*
`;

  fs.writeFileSync(mdPath, markdown, 'utf-8');
  console.log(`Markdown summary report saved to: ${mdPath}`);
  return summary;
}

runBenchmark();
